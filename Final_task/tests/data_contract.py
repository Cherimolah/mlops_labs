"""
data_contract.py — описание «контракта данных» для проекта.

Здесь в одном месте собраны инварианты, на которые опирается ML-пайплайн
(train.py, drift_detection.py, model.py). Тесты качества данных
(tests/test_data_quality.py) импортируют этот модуль и проверяют, что свежий
датасет этим инвариантам удовлетворяет.

Контракт сознательно делится на два уровня:

  * STRICT  — нарушение ломает обучение/инференс. Тест обязан падать.
              (нет нужной колонки, таргет пустой/неположительный и т.п.)
  * SOFT    — данные «грязные» по своей природе (это сырые данные Kaggle),
              но если доля пропусков/мусора вырастает выше потолка — это
              сигнал, что скачался битый файл. Тест падает только при выходе
              за щедрый порог.

Пороги подобраны по реальному train.csv (15 092 строки): максимальная доля
пропусков в признаке ~0.11 (build_year), поэтому потолок 0.5 ловит реальную
поломку, не мешая нормальным данным.
"""

# Колонки, которые train.py / drift_detection.py ожидают увидеть.
REQUIRED_COLUMNS = [
    "full_sq", "life_sq", "floor", "max_floor", "build_year",
    "num_room", "kitch_sq", "sub_area", "price_doc",
]

# Имя целевой переменной.
TARGET = "price_doc"

# Колонки, которые НЕ должны содержать пропусков (на них опирается обучение
# напрямую: target и ключ кодировщика района; full_sq — главный признак).
NON_NULL_COLUMNS = ["price_doc", "sub_area", "full_sq"]

# «Мягкие» признаки: пропуски допустимы (train.py заполняет медианой),
# но их доля не должна превышать потолок.
SOFT_NULLABLE_COLUMNS = [
    "life_sq", "floor", "max_floor", "build_year", "num_room", "kitch_sq",
]
MAX_NULL_FRACTION = 0.5

# Минимальное число строк, при котором обучение имеет смысл.
MIN_ROWS = 1000

# Здравые границы для главного признака площади (м²). Сырые данные содержат
# выбросы, поэтому проверяем не «все значения», а что МЕДИАНА в норме —
# это ловит подмену единиц измерения или сдвиг колонок.
FULL_SQ_MEDIAN_RANGE = (20.0, 120.0)
